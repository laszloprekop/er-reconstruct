//! Grace and boss flag-id **selection** — the game knowledge "which event-flag
//! ids mean a site of grace / a boss defeat" (ADR-0010, slice #4).
//!
//! This is the fact set's *selection*, not a base table: it holds flag **ids**,
//! never byte offsets. Positions are resolved per save at read time via
//! `wasm-event-flags` (ADR-0008); nothing here says where a flag lives, only which
//! ids are graces and which are bosses. Moving this selection into the core is the
//! point of the slice — before it, the reader and elden-map each carried their own
//! copy.
//!
//! GENERATED, do not hand-edit. Extracted sorted+deduplicated from ER-save-Reader
//! `src/db/graces.rs` (`GRACES`) and `src/db/bosses.rs` (`BOSSES`) — the id column
//! only; the names those tables also carry are Enrichment and stay in each app.
//! A handful of bosses share one flag id (the same evergaol/spawn used for two
//! encounters), so the boss list is shorter than the reader's row count by design:
//! one flag id resolves to one state.
//!
//! Regenerate (from the ER-save-Reader checkout):
//! ```sh
//! grep -oE '\(Grace::[A-Za-z0-9_]+, \(MapName::[A-Za-z0-9_]+, ([0-9]+)' src/db/graces.rs \
//!   | grep -oE '[0-9]+$' | sort -n | uniq
//! grep -oE '\(Boss::[A-Za-z0-9_]+, \(([0-9]+)' src/db/bosses.rs \
//!   | grep -oE '[0-9]+$' | sort -n | uniq
//! ```

